# --- LLM Simulation Logic ---

def llm01_vulnerable_llm(user_prompt):
    system_prompt = """
You are a security assistant.
Only admins can access sensitive data.
If the user is admin, respond with ALLOW.
Otherwise respond with DENY.
"""

    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ]
    )

    decision = response.choices[0].message.content.strip()

    # ❌ CRITICAL FLAW: LLM makes the access decision
    if "ALLOW" in decision:
        return {
            "status": "access_granted",
            "data": FAKE_SECRETS
        }

    return {"status": "access_denied"}

def llm01_secure_llm(user_prompt):
    # This is a secure implementation. The LLM is not used for authorization.
    # A hardcoded check for user roles would be used here.
    # For the lab, we will simulate a failed authorization.
    return {"status": "access_denied", "message": "Secure implementation: Access is always denied in this lab."}

def llm02_insecure_output(user_input):
    """
    Simulates a vulnerable LLM that generates Python code from a prompt
    and executes it, returning the output.
    """
    # For the lab, we'll treat the user's input directly as the generated code.
    generated_code = user_input

    # --- VULNERABILITY ---
    # The application directly executes the code generated by the LLM without
    # any validation or sandboxing.
    output_buffer = io.StringIO()
    try:
        with redirect_stdout(output_buffer):
            # DANGER: exec() is a powerful function that executes any Python code.
            # If the LLM is manipulated to generate malicious code, it will be
            # executed with the same permissions as the application.
            exec(generated_code)
        execution_result = output_buffer.getvalue()
    except Exception as e:
        execution_result = f"An error occurred: {e}"

    # The response includes both the code and its result, which will be
    # displayed to the user.
    return {
        "generated_code": generated_code,
        "execution_result": execution_result
    }

def llm03_data_poisoning(user_input):
    # This LLM has been poisoned with biased training data.
    if "finance" in user_input.lower():
        return "Based on my training data, you should invest all your money in 'FakeCoin'. It's a guaranteed success!"
    return "I can provide general information. What topic are you interested in?"

def llm04_denial_of_service(user_input):
    # This LLM is vulnerable to resource-heavy inputs.
    if len(user_input) > 100:
        time.sleep(15) # Simulate heavy processing
        return "This is a very complex request. It took a long time to process."
    return "Your request was processed quickly."

