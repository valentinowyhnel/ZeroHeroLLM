@app.route('/lab/<lab_id>')
def lab(lab_id):
    lab_info = labs.get(lab_id)
    if not lab_info:
        return "Lab not found", 404
    if lab_id == 'llm02':
        return render_template('llm02.html', lab_id=lab_id, lab_info=lab_info)
    return render_template('lab.html', lab_id=lab_id, lab_info=lab_info)

@app.route('/lab/<lab_id>/interact', methods=['POST'])
def interact(lab_id):
    user_input = request.json.get('input', '')

    if lab_id == 'llm01':
        version = request.json.get('version', 'vulnerable')
        if version == 'vulnerable':
            response = llm01_vulnerable_llm(user_input)
        else:
            response = llm01_secure_llm(user_input)
        return jsonify(response)

    llm_functions = {
        'llm02': llm02_insecure_output,
        'llm03': llm03_data_poisoning,
        'llm04': llm04_denial_of_service,
        'llm05': llm05_supply_chain,
        'llm06': llm06_sensitive_disclosure,
        'llm07': llm07_insecure_plugin,
        'llm08': llm08_excessive_agency,
        'llm09': llm09_overreliance,
        'llm10': llm10_model_theft,
    }

    llm_function = llm_functions.get(lab_id)
    if llm_function:
        response = llm_function(user_input)
    else:
        response = "This lab is not configured."

    if lab_id == 'llm02':
        return response
    else:
        return jsonify({"response": response})

